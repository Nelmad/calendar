import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {primaryIdentifiers, intersectCapabilities, sha256, listHash} from './primary.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const read = path => readFileSync(resolve(here, path));
const policy = JSON.parse(read('policy.json'));
if (policy.status !== 'candidate' || policy.releaseMatrixComplete !== false) throw new Error('RC freeze needs the T27 exact tuple gate; this runner only generates candidates');
if (sha256(read(policy.tzdb.archive)) !== policy.tzdb.sha256) throw new Error('tzdb archive checksum mismatch');
const inputs = {};
const extract = name => {
    if (!/^[a-zA-Z0-9.-]+$/.test(name)) throw new Error('Invalid input filename');
    const value = execFileSync('tar', ['-xOf', resolve(here, policy.tzdb.archive), name], {encoding: 'utf8', maxBuffer: 4 * 1024 * 1024});
    inputs[name] = sha256(value);
    return value;
};
if (extract('version').trim() !== policy.tzdb.version) throw new Error('tzdb version mismatch');
const sources = policy.tzdb.sources.map(extract);
const primary = primaryIdentifiers(sources, extract('zone.tab'), extract('backzone'), policy.renamePolicy.pending);
// Keep reviewed rename history and build configuration fingerprinted as inputs.
extract('NEWS'); extract('Makefile'); extract('LICENSE');
const reports = policy.runtimeReports.map(({path, sha256: expected}) => {
    const bytes = read(path);
    if (sha256(bytes) !== expected) throw new Error(`Runtime report checksum mismatch: ${path}`);
    return JSON.parse(bytes);
});
const accepted = intersectCapabilities(primary.identifiers, reports, policy.requiredMinimum);
const manifest = {
    schemaVersion: 1, status: 'candidate', releaseLine: '0.2.x', frozen: false,
    tzdb: {...policy.tzdb, inputHashes: inputs}, standard: policy.standard, renamePolicy: policy.renamePolicy,
    generator: {revision: 1, files: Object.fromEntries(['generate.mjs', 'primary.mjs', 'policy.json'].map(file => [file, sha256(read(file))]))},
    requiredMinimum: policy.requiredMinimum, runtimeReports: policy.runtimeReports, releaseMatrixComplete: false,
    allIdentifiers: primary.all, primaryIdentifiers: primary.identifiers, primaryLinks: primary.primaryLinks,
    primaryListSha256: listHash(primary.identifiers), identifiers: accepted.identifiers,
    listSha256: listHash(accepted.identifiers), hashEncoding: 'UTF-8 identifiers joined by LF, including final LF',
    exclusions: [...primary.exclusions, ...accepted.exclusions].sort((a, b) => a.identifier < b.identifier ? -1 : 1),
};
const moduleText = `// Generated by scripts/implementation/timezones/generate.mjs. Do not edit.\n// Private 0.2 candidate; RC runtime matrix and freeze remain open.\n// IANA tzdb ${policy.tzdb.version}, ECMA-402 edition 12; list SHA-256 ${manifest.listSha256}.\nexport const acceptedTimeZoneIdentifiers: readonly string[] = Object.freeze(\n    '${accepted.identifiers.join(' ')}'.split(' '),\n);\n`;
const docs = (language) => language === 'ru'
    ? `# Допустимые timezone — кандидат 0.2\n\nЭто private candidate, не RC freeze. tzdb ${policy.tzdb.version}, ECMA-402 edition 12. Полная runtime matrix ещё не проверена.\n\nИмена принимаются посимвольно, включая регистр. Aliases вне списка отклоняются. См. [manifest](timezones-candidate.json) для источников, исключений и evidence.\n\n${accepted.identifiers.length} identifiers; SHA-256 списка: \`${manifest.listSha256}\`.\n\n\`\`\`text\n${accepted.identifiers.join('\n')}\n\`\`\`\n`
    : `# Accepted time zones — 0.2 candidate\n\nThis is a private candidate, not the RC freeze. tzdb ${policy.tzdb.version}, ECMA-402 edition 12. The complete runtime matrix is still pending.\n\nIdentifiers are accepted exactly, including case. Aliases outside this list are rejected. See the [manifest](timezones-candidate.json) for inputs, exclusions and evidence.\n\n${accepted.identifiers.length} identifiers; list SHA-256: \`${manifest.listSha256}\`.\n\n\`\`\`text\n${accepted.identifiers.join('\n')}\n\`\`\`\n`;
for (const [path, content] of [
    ['src/v02/core/timeZones.generated.ts', moduleText],
    ['docs/implementation/timezones-candidate.json', JSON.stringify(manifest, null, 2) + '\n'],
    ...['en', 'ru'].map(lang => [`docs/implementation/timezones-candidate.${lang}.md`, docs(lang)]),
]) {
    const target = resolve(root, path);
    if (process.argv.includes('--write')) { mkdirSync(dirname(target), {recursive: true}); writeFileSync(target, content); }
    else if (readFileSync(target, 'utf8') !== content) throw new Error(`Generated file is stale: ${path}`);
}
console.log(`Timezone candidate: ${accepted.identifiers.length}/${primary.identifiers.length} primary IDs; ${manifest.listSha256}`);
